function convertBengaliNumber(bengaliStr) {
    const bengaliToEnglish = {
        '০': '0', '১': '1', '২': '2', '৩': '3', '৪': '4',
        '৫': '5', '৬': '6', '৭': '7', '৮': '8', '৯': '9'
    };
    let engStr = '';
    for (let i = 0; i < bengaliStr.length; i++) {
        engStr += bengaliToEnglish[bengaliStr[i]] || bengaliStr[i];
    }
    return parseInt(engStr, 10) || 0;
}

